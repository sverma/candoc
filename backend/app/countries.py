COUNTRY_CODES = frozenset(COUNTRY_NAMES)
REGION_CODES = frozenset(REGION_NAMES)
CURRENCY_CODES = frozenset(CURRENCY_NAMES)


def _validate(code, allowed, label):
    if not isinstance(code, str) or code.strip().upper() not in allowed:
        raise ValueError('Choose a valid ' + label + ' code.')
    return code.strip().upper()


def validate_country(code):
    return _validate(code, COUNTRY_CODES, 'ISO country/territory')


def validate_region(code):
    return _validate(code, REGION_CODES, 'geographic region')


def validate_currency(code):
    return _validate(code, CURRENCY_CODES, 'ISO currency')


def _choices(values):
    return [{'value': value, 'label': value.replace('_', ' ').capitalize()} for value in values]


def catalogs():
    return {
        'countries': sorted([{'code': code, 'name': name} for code, name in COUNTRY_NAMES.items()], key=lambda item: item['name']),
        'regions': [{'code': code, 'name': name} for code, name in REGION_NAMES.items()],
        'currencies': sorted([{'code': code, 'name': name} for code, name in CURRENCY_NAMES.items()], key=lambda item: item['code']),
        'engagement_types': _choices(ENGAGEMENT_TYPES), 'work_modes': _choices(WORK_MODES),
        'time_commitments': _choices(TIME_COMMITMENTS), 'support_types': _choices(SUPPORT_TYPES),
        'pay_periods': _choices(PAY_PERIODS), 'experience_levels': _choices(EXPERIENCE_LEVELS),
        'geography_notice': 'Countries and regions describe geographic preferences, never work authorization or legal eligibility.',
    }
